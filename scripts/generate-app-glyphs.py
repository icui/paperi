#!/usr/bin/env python3
"""Generates Sources/PaperiPlatform/AppGlyphs.swift from sketchybar-app-font's
icon_map.lua (https://github.com/kvndrsslr/sketchybar-app-font), mapping app
names to the font's ligatures.

usage: scripts/generate-app-glyphs.py path/to/icon_map.lua
"""
import pathlib
import re
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
entry = re.compile(r'^\s*\[ \[\[(.*)\]\] \] = "(:[A-Za-z0-9_-]+:)",\s*$')
pairs = {}
for line in pathlib.Path(sys.argv[1]).read_text(encoding="utf-8").splitlines():
    match = entry.match(line)
    if match:
        pairs.setdefault(match.group(1), match.group(2))
if not pairs:
    sys.exit("no entries found")


def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = pathlib.Path(__file__).resolve().parent.parent / "Sources/PaperiPlatform/AppGlyphs.swift"
lines = [
    "// Generated by scripts/generate-app-glyphs.py from sketchybar-app-font's",
    "// icon_map.lua. Do not edit by hand.",
    "",
    "/// App names (as `NSRunningApplication.localizedName` reports them) to",
    "/// sketchybar-app-font ligatures.",
    "enum AppGlyphs {",
    "    static let ligatures: [String: String] = [",
]
lines += [f"        {swift(name)}: {swift(glyph)}," for name, glyph in pairs.items()]
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {len(pairs)} entries to {out}")
